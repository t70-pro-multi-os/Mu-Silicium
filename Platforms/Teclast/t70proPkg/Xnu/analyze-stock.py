"""Extract the verified offline stock CPU/GIC/timer description, without RAM guesses."""
import copy
import hashlib
import json
import os
from pathlib import Path
import subprocess
import struct
import sys
import tempfile

here = Path(__file__).resolve().parent
repo = here.parents[3]
project = repo.parent
if "--locked" not in sys.argv:
    os.execv(str(repo / "Resources/Scripts/with-build-lock"),
             ["with-build-lock", "T70Pro", "Analyze stock XNU platform", "--",
              sys.executable, str(Path(__file__).resolve()), "--locked"])
subprocess.run([sys.executable, str(here / "prepare-sources.py"), "--check"], check=True)
sys.dont_write_bytecode = True
sys.path.insert(0, str(project / "xnu-sources/UniXNU/scripts"))
from unixnu.devicetree import read_fdt, registers, generate, hardware_properties, arm_io_window
from unixnu.util import Error

stock = project / "analysis/stock-fdt"
expected = {
    "base.dtb": "c42433faf6996c2ba7b6d4d745ce69b5a1723ea4dcb44cbff631ac2710a396f6",
    "board.dtbo": "b64e9993e30179d572aeb702b645ea26ead5b1a63bf98121688e09154cf1def2",
    "effective.dtb": "a3dd45e28ee284f1995374091eca9634f68c88dfddc5ecd27a37cdcc877dd391",
}
def require(condition, message):
    if not condition:
        raise ValueError(message)

def child(parent, name):
    matches = [n for n in parent.children if n.name == name]
    require(len(matches) == 1, "Missing/ambiguous node: " + name)
    return matches[0]

def facts(root):
    require(root.strings("compatible") == ["mediatek,MT6789"], "Wrong stock SoC")
    cpus = child(root, "cpus")
    cores = [n for n in cpus.children if n.strings("device_type") == ["cpu"] and n.enabled()]
    require([n.scalar("reg") for n in cores] == [i << 8 for i in range(8)], "Unexpected CPU MPIDRs")
    require([n.strings("compatible") for n in cores] == [["arm,cortex-a55"]]*6 + [["arm,cortex-a76"]]*2,
            "Unexpected CPU types")
    require(all(n.strings("enable-method") == ["psci"] for n in cores), "Unexpected CPU start method")
    psci, gic, timer = [child(root, name) for name in ("psci", "interrupt-controller", "timer")]
    require(psci.strings("compatible") == ["arm,psci-1.0"] and psci.strings("method") == ["smc"], "PSCI 1.0 SMC required")
    require(gic.strings("compatible") == ["arm,gic-v3"] and gic.scalar("#interrupt-cells") == 4,
            "Unexpected GIC binding")
    require(registers(gic) == [(0xc000000, 0x40000), (0xc040000, 0x200000)], "Unexpected GIC resources")
    require("redistributor-stride" not in gic.properties, "Review newly supplied GICR stride")
    require(gic.scalar("#redistributor-regions") == 1 and gic.cells("interrupts") == [1,9,4,0],
            "Unexpected GIC redistributor region or maintenance interrupt")
    require(timer.strings("compatible") == ["arm,armv8-timer"], "Unexpected timer type")
    irq = timer.cells("interrupts")
    require(irq == [1,13,4,0, 1,14,4,0, 1,11,4,0, 1,10,4,0], "Unexpected timer interrupts")
    require(timer.scalar("clock-frequency") == 13000000, "Unexpected timer frequency")
    return {
        "cpus": [{"mpidr": n.scalar("reg"), "compatible": n.strings("compatible")[0],
                  "cluster_type": "E" if i < 6 else "P"} for i,n in enumerate(cores)],
        "cluster_type_basis": "software E/P grouping from CPU type; not physical AFF1 clusters",
        "gic": {"compatible": "arm,gic-v3", "reg": registers(gic), "interrupt_cells": 4,
                "redistributor_regions": gic.scalar("#redistributor-regions"), "redistributor_stride": None,
                "maintenance_interrupt": gic.cells("interrupts"), "cpu_frame_mapping": "unverified"},
        "timer": {"frequency_hz": timer.scalar("clock-frequency"), "runtime_cntfrq_verified": False,
                  "cpu_timebase_basis": "/timer/clock-frequency; /cpus/timebase-frequency is absent in stock",
                  "interrupts": irq,
                  "intids": [irq[i+1]+16 for i in range(0,len(irq),4)]},
        "psci": {"compatible": psci.strings("compatible"), "method": "smc", "execution": "not_run"},
    }

def dts(info):
    cpu_lines = []
    for cpu in info["cpus"]:
        cpu_lines.append('        cpu@%x { device_type = "cpu"; compatible = "%s"; reg = <0x%x>; '
                         'enable-method = "psci"; unixnu,cluster-type = "%s"; };' %
                         (cpu["mpidr"],cpu["compatible"],cpu["mpidr"],cpu["cluster_type"]))
    return ('/dts-v1/;\n'
        '/* Generated by analyze-stock.py from effective.dtb SHA-256 ' + expected["effective.dtb"] + '.\n'
        ' * Board model is a target label; CPU timebase comes from /timer/clock-frequency.\n'
        ' * Hardware-only: runtime RAM/reservations and GOP must be supplied separately. */\n'
        '/ {\n    model = "Teclast T70 Pro"; compatible = "mediatek,MT6789";\n'
        '    #address-cells = <2>; #size-cells = <2>; interrupt-parent = <&gic>;\n'
        '    cpus {\n        #address-cells = <1>; #size-cells = <0>; timebase-frequency = <13000000>;\n' +
        '\n'.join(cpu_lines) + '\n    };\n'
        '    psci { compatible = "arm,psci-1.0"; method = "smc"; };\n'
        '    gic: interrupt-controller@c000000 {\n'
        '        unixnu,adt-name = "intc"; compatible = "arm,gic-v3";\n'
        '        interrupt-controller; #interrupt-cells = <4>; #address-cells = <2>; #size-cells = <2>; ranges;\n'
        '        reg = <0 0xc000000 0 0x40000>, <0 0xc040000 0 0x200000>;\n'
        '        #redistributor-regions = <1>; interrupts = <1 9 4 0>;\n'
        '    };\n'
        '    timer { unixnu,adt-name = "timer"; compatible = "arm,armv8-timer";\n'
        '        clock-frequency = <13000000>;\n'
        '        interrupts = <1 13 4 0>, <1 14 4 0>, <1 11 4 0>, <1 10 4 0>;\n'
        '    };\n};\n')

hashes = {name: hashlib.sha256((stock/name).read_bytes()).hexdigest() for name in expected}
require(hashes == expected, "Stock DTB hashes changed; inspect new firmware before updating pins")
root = read_fdt((stock / "effective.dtb").read_bytes())
info = facts(root)
# Reject changed CPU identities, interrupt bindings, or PSCI conduits before producing board input.
for node, prop, value in (("cpus", "reg", bytes(4)), ("timer", "interrupts", bytes(4)),
                          ("psci", "method", b"hvc\0"),
                          ("interrupt-controller", "#redistributor-regions", b"\0\0\0\2")):
    modified = copy.deepcopy(root)
    target = child(modified, node)
    if node == "cpus":
        target = [n for n in target.children if n.strings("device_type") == ["cpu"]][1]
    target.properties[prop] = value
    try:
        facts(modified)
    except ValueError:
        pass
    else:
        raise AssertionError("Altered hardware was accepted: " + node)

build = repo / "Build/t70proPkg/XnuPlatform"
build.mkdir(parents=True, exist_ok=True)
source = here / "t70pro-hardware.dts"
source.write_text(dts(info))
compiled = build / "t70pro-hardware.dtb"
with tempfile.TemporaryDirectory(prefix="stock-xnu-", dir=build) as temp:
    composed = Path(temp) / "effective.dtb"
    subprocess.run(["fdtoverlay", "-i", str(stock/"base.dtb"), "-o", str(composed), str(stock/"board.dtbo")], check=True)
    require(hashlib.sha256(composed.read_bytes()).hexdigest() == expected["effective.dtb"],
            "Reapplied stock overlay differs from the recorded effective DTB")
subprocess.run(["dtc", "-I", "dts", "-O", "dtb", "-o", str(compiled), str(source)], check=True)
roundtrip = read_fdt(compiled.read_bytes())
require([n.scalar("reg") for n in child(roundtrip,"cpus").children] == [n["mpidr"] for n in info["cpus"]],
        "DTS round-trip changed CPU affinities")
require([n.strings("unixnu,cluster-type") for n in child(roundtrip,"cpus").children] == [["E"]]*6 + [["P"]]*2,
        "DTS round-trip changed the E/P inputs used by the pinned ADT converter")
require(child(roundtrip,"cpus").scalar("timebase-frequency") == info["timer"]["frequency_hz"],
        "DTS timebase differs from the stock timer declaration")
require(registers(child(roundtrip,"interrupt-controller@c000000")) == [tuple(p) for p in info["gic"]["reg"]],
        "DTS round-trip changed GIC resources")
# ArmCpu resolves this exact IODT path when it probes the GIC.
intc = child(roundtrip, "interrupt-controller@c000000")
require(intc.strings("unixnu,adt-name") == ["intc"], "ArmCpu requires /arm-io/intc")
handles = {entry.scalar("phandle"): entry for entry in roundtrip.walk() if "phandle" in entry.properties}
exports = [entry for entry in roundtrip.walk() if "unixnu,adt-name" in entry.properties and entry.enabled()]
base, _ = arm_io_window(exports)
adt_intc = dict(hardware_properties(intc, handles, base))
require(adt_intc["compatible"] == b"arm,gic-v3\0", "GIC compatible changed during ADT conversion")
require(adt_intc["reg"] == b"".join(struct.pack("<QQ", address-base, size) for address,size in registers(intc)),
        "GIC ADT register offsets do not resolve through arm-io ranges")
info["gic"]["adt_path"] = "/arm-io/intc"
info["gic"]["adt_binding_check"] = "compiled DTB name and pinned converter compatible/register ranges"
# Deliberately missing RAM must prevent this static description becoming a bootable ADT.
try:
    generate(compiled, {})
except Error as error:
    require(str(error) == "ADT handoff requires one contiguous DRAM range", str(error))
else:
    raise AssertionError("Hardware-only DTS was accepted as a bootable ADT")
inventory = json.loads((stock/"inventory.json").read_text())
reserved = child(root, "reserved-memory")
info.update({"status": "offline_platform_verified", "input_sha256": hashes,
    "checks": ["stock hashes", "overlay reproduction", "CPU/IRQ/PSCI rejection cases", "DTS compilation/round-trip", "incomplete ADT rejection"],
    "source_image_hash_rechecked": False, "runtime_fixups_verified": False,
    "recorded_offline_overlay_applied": inventory.get("offline_overlay_applied"),
    "static_memory_reg": registers(child(root,"memory")), "static_memory_is_runtime_evidence": False,
    "stock_model": root.strings("model"), "generated_model": "Teclast T70 Pro",
    "generated_model_basis": "target board label; not the stock /model property",
    "uart": [{"node": n.name, "reg": registers(n), "status_declared": "status" in n.properties,
        "baud_declared": "current-speed" in n.properties, "clock_frequency_declared": "clock-frequency" in n.properties}
        for n in root.walk() if "mediatek,mt6577-uart" in n.strings("compatible")],
    "uart_exported_to_xnu": False, "selected_debug_uart": "unverified",
    "extractor_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    "reserved_memory": [{"name": n.name, "has_fixed_reg": "reg" in n.properties,
        "size_cells": n.cells("size"), "alignment_cells": n.cells("alignment")} for n in reserved.children],
    "bootable_adt": "not_generated_requires_verified_runtime_memory_and_reservations",
    "kernel_build_report": str(project / "analysis/xnu-kernel-build.json"), "device_boot": "not_run",
    "dts": str(source), "dts_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "dtb": str(compiled), "dtb_sha256": hashlib.sha256(compiled.read_bytes()).hexdigest()})
report = project / "analysis/xnu-stock-platform.json"
report.write_text(json.dumps(info, indent=2) + "\n")
print("PASS: stock overlay, eight CPUs, GICv3, PSCI SMC, 13 MHz timer; incomplete ADT refused")
print("Report:", report)
